import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {resolveRenderBrowser,resolveRenderPublic} from '../src/render-browser.mjs';
import {loadRenderLibraries} from '../src/render-runtime.mjs';
import {validateRenderInput} from './render-input.mjs';
const here=path.dirname(fileURLToPath(import.meta.url)),base=path.dirname(here);
const [propsFile,out,format='MetalRustLandscape']=process.argv.slice(2);
if(!propsFile||!out||!['MetalRustLandscape','MetalRustShorts','MetalRustCleanShorts'].includes(format))throw Error('Usage: metal_rust/render.mjs actual-props.json NEW_OUTPUT MetalRustLandscape|MetalRustShorts|MetalRustCleanShorts');
if(fs.existsSync(out))throw Error('Preserve existing Rust output');
const contract=JSON.parse(fs.readFileSync(path.join(here,'contract.json'),'utf8'));
const inputProps=validateRenderInput(JSON.parse(fs.readFileSync(propsFile,'utf8')),contract);
if(inputProps.burnCaptions!==(format==='MetalRustShorts'))throw Error('Wrong destination caption layer');
const browserExecutable=resolveRenderBrowser();
const {bundle,selectComposition,renderMedia,runtimeRoot}=await loadRenderLibraries(base);
const serveUrl=await bundle({entryPoint:path.join(here,'index.tsx'),publicDir:resolveRenderPublic(base),rootDir:runtimeRoot});
const composition=await selectComposition({serveUrl,id:format,inputProps,browserExecutable});
fs.mkdirSync(path.dirname(path.resolve(out)),{recursive:true});
await renderMedia({serveUrl,composition,inputProps,browserExecutable,outputLocation:out,codec:'h264',pixelFormat:'yuv420p',colorSpace:'bt709',crf:20,disableSharedMemoryCapture:true,imageFormat:'png',concurrency:4});
console.log('PRIVATE SILENT RUST BODY ONLY; actual AV/rights/listening/release remain separate. Common compositor appends exact END and selected soundtrack once.');
